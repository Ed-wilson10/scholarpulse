class Command(BaseCommand):
    help = "Seed categories, opportunities and a demo admin account."

    def handle(self, *args, **options):
        cats = {}
        for name, slug, color, icon, desc in CATEGORIES:
            cat, _ = Category.objects.update_or_create(
                slug=slug,
                defaults={"name": name, "color": color, "icon": icon, "description": desc},
            )
            cats[slug] = cat

        created = 0
        updated = 0
        for item in DATA:
            item = dict(item)
            cat_slug = item.pop("category", None)
            item["category"] = cats.get(cat_slug)
